// SingleArgs returns argv (without the binary) for a standalone server.
func SingleArgs(r config.Resolved, host string, port int) []string {
	args := []string{
		"--model", r.ModelPath,
		"--host", host,
		"--port", strconv.Itoa(port),
	}
	if r.Alias != "" {
		args = append(args, "--alias", r.Alias)
	}
	if r.Ctx > 0 {
		args = append(args, "-c", strconv.Itoa(r.Ctx))
	}
	args = append(args, "--gpu-layers", strconv.Itoa(r.GPULayers))
	if r.NCPUMoE > 0 {
		args = append(args, "--n-cpu-moe", strconv.Itoa(r.NCPUMoE))
	}
	if r.Threads > 0 {
		args = append(args, "--threads", strconv.Itoa(r.Threads))
	}
	if r.ThreadsBatch > 0 {
		args = append(args, "--threads-batch", strconv.Itoa(r.ThreadsBatch))
	}
	if r.BatchSize > 0 {
		args = append(args, "--batch-size", strconv.Itoa(r.BatchSize))
	}
	if r.UBatchSize > 0 {
		args = append(args, "--ubatch-size", strconv.Itoa(r.UBatchSize))
	}
	if r.Parallel > 0 {
		args = append(args, "--parallel", strconv.Itoa(r.Parallel))
	}
	if r.FlashAttn != "" {
		args = append(args, "--flash-attn", r.FlashAttn)
	}
	if r.CacheTypeK != "" {
		args = append(args, "--cache-type-k", r.CacheTypeK)
	}
	if r.CacheTypeV != "" {
		args = append(args, "--cache-type-v", r.CacheTypeV)
	}
	if r.Jinja {
		args = append(args, "--jinja")
	} else {
		args = append(args, "--no-jinja")
	}
	if r.Metrics {
		args = append(args, "--metrics")
	}
	args = append(args, samplingArgs(r.Sampling)...)
	args = append(args, extraArgs(r.Extra)...)
	return args
}

func samplingArgs(s config.Sampling) []string {
	return []string{
		"--temp", formatFloat(s.Temp),
		"--top-p", formatFloat(s.TopP),
		"--top-k", strconv.Itoa(s.TopK),
		"--min-p", formatFloat(s.MinP),
		"--repeat-penalty", formatFloat(s.RepeatPenalty),
		"--presence-penalty", formatFloat(s.PresencePenalty),
		"--frequency-penalty", formatFloat(s.FrequencyPenalty),
		"--typical-p", formatFloat(s.TypicalP),
		"--mirostat", strconv.Itoa(s.Mirostat),
		"--seed", strconv.Itoa(s.Seed),
	}
}

// extraArgs turns config extra keys into flags. A key may be written with or
// without leading dashes; an empty value produces a bare flag.
func extraArgs(extra map[string]string) []string {
	normalized := config.NormalizeExtraMap(extra)
	var args []string
	for _, flag := range config.ExtraFlags(extra) {
		args = append(args, "--"+flag)
		if v := normalized[flag]; v != "" {
			args = append(args, v)
		}
	}
	return args
}

// RouterArgs returns argv for router mode. Per-model options come from the
// generated INI, never from the command line, because CLI flags would
// override every preset.
func RouterArgs(cfg *config.Config, host string, port int, iniPath string) []string {
	args := []string{
		"--host", host,
		"--port", strconv.Itoa(port),
		"--models-preset", iniPath,
		"--models-max", strconv.Itoa(cfg.Router.ModelsMax),
	}
	if cfg.Router.Autoload {
		args = append(args, "--models-autoload")
	} else {
		args = append(args, "--no-models-autoload")
	}
	if cfg.Router.SleepIdleSeconds >= 0 {
		args = append(args, "--sleep-idle-seconds", strconv.Itoa(cfg.Router.SleepIdleSeconds))
	}
	if cfg.Router.MetricsEnabled() {
		args = append(args, "--metrics")
	}
	if cfg.Router.MemoryMarginMiB > 0 {
		margin := strconv.Itoa(cfg.Router.MemoryMarginMiB)
		args = append(args, "--fit-target", margin, "--models-memory-margin", margin)
	}
	return append(args, cfg.Router.ExtraArgs...)
}

// RenderRouterINI renders one preset section per model plus a [*] section
// holding the shared defaults. Sections are sorted for deterministic output.
func RenderRouterINI(cfg *config.Config) ([]byte, error) {
	defaults := cfg.ResolveDefaults()
	var b strings.Builder

	b.WriteString("# Generated by wool. Edits here are overwritten.\n")
	b.WriteString("[*]\n")
	writeCommonINI(&b, defaults, defaults.Extra)
	writeExtraINI(&b, defaults.Extra)
	if cfg.Router.Autoload {
		b.WriteString("load-on-startup = true\n")
	}
	for _, id := range cfg.ModelIDs() {
		r, err := cfg.Resolve(id, nil)
		if err != nil {
			return nil, err
		}
		if err := validateINISection(id); err != nil {
			return nil, err
		}
		extra := cfg.Models[id].Options.Extra
		overrides := iniFieldOverrides(extra)
		b.WriteString("\n[" + id + "]\n")
		if !overrides["model"] {
			b.WriteString("model = " + iniValue(r.ModelPath) + "\n")
		}
		if r.Alias != "" && !overrides["alias"] {
			b.WriteString("alias = " + iniValue(r.Alias) + "\n")
		}
		writeCommonINI(&b, r, extra)
		// Only this model's layer is written here; inherited extras already
		// come from [*]. Resolved r.Extra would repeat every default.
		writeExtraINI(&b, extra)
	}
	return []byte(b.String()), nil
}

// WriteRouterINI writes the generated INI atomically, creating parent dirs.
func WriteRouterINI(cfg *config.Config, path string) error {
	data, err := RenderRouterINI(cfg)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".models-*.ini")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	defer os.Remove(tmpName)
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Chmod(0o600); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmpName, path)
}

// writeExtraINI writes one INI key per extra flag. An empty TOML value is a
// bare CLI flag, which the INI form represents as true.
func writeExtraINI(b *strings.Builder, extra map[string]string) {
	normalized := config.NormalizeExtraMap(extra)
	for _, flag := range config.ExtraFlags(extra) {
		value := normalized[flag]
		if value == "" {
			value = "true"
		}
		b.WriteString(iniValue(flag) + " = " + iniValue(value) + "\n")
	}
}

// iniOptionFields maps a generated INI key to the config field it represents.
// An extra that conflicts with one of these fields replaces the generated line
// instead of producing a duplicate key.
var iniOptionFields = map[string]string{
	"ctx-size":          "ctx",
	"gpu-layers":        "gpu_layers",
	"n-cpu-moe":         "n_cpu_moe",
	"threads":           "threads",
	"threads-batch":     "threads_batch",
	"batch-size":        "batch_size",
	"ubatch-size":       "ubatch_size",
	"parallel":          "parallel",
	"flash-attn":        "flash_attn",
	"cache-type-k":      "cache_type_k",
	"cache-type-v":      "cache_type_v",
	"jinja":             "jinja",
	"temp":              "sampling.temp",
	"top-p":             "sampling.top_p",
	"top-k":             "sampling.top_k",
	"min-p":             "sampling.min_p",
	"repeat-penalty":    "sampling.repeat_penalty",
	"presence-penalty":  "sampling.presence_penalty",
	"frequency-penalty": "sampling.frequency_penalty",
	"typical-p":         "sampling.typical_p",
	"mirostat":          "sampling.mirostat",
	"seed":              "sampling.seed",
}

func iniFieldOverrides(extra map[string]string) map[string]bool {
	overrides := make(map[string]bool)
	for _, conflict := range config.ExtraConflicts(extra) {
		overrides[conflict.Field] = true
	}
	return overrides
}

// writeCommonINI writes launch options shared by the globals and each model.
func writeCommonINI(b *strings.Builder, r config.Resolved, extra map[string]string) {
	overrides := iniFieldOverrides(extra)
	write := func(key, value string) {
		if field, ok := iniOptionFields[key]; ok && overrides[field] {
			return
		}
		b.WriteString(key + " = " + value + "\n")
	}
	if r.Ctx > 0 {
		write("ctx-size", strconv.Itoa(r.Ctx))
	}
	write("gpu-layers", strconv.Itoa(r.GPULayers))
	if r.NCPUMoE > 0 {
		write("n-cpu-moe", strconv.Itoa(r.NCPUMoE))
	}
	if r.Threads > 0 {
		write("threads", strconv.Itoa(r.Threads))
	}
	if r.ThreadsBatch > 0 {
		write("threads-batch", strconv.Itoa(r.ThreadsBatch))
	}
	if r.BatchSize > 0 {
		write("batch-size", strconv.Itoa(r.BatchSize))
	}
	if r.UBatchSize > 0 {
		write("ubatch-size", strconv.Itoa(r.UBatchSize))
	}
	if r.Parallel > 0 {
		write("parallel", strconv.Itoa(r.Parallel))
	}
	if r.FlashAttn != "" {
		write("flash-attn", iniValue(r.FlashAttn))
	}
	if r.CacheTypeK != "" {
		write("cache-type-k", iniValue(r.CacheTypeK))
	}
	if r.CacheTypeV != "" {
		write("cache-type-v", iniValue(r.CacheTypeV))
	}
	write("jinja", strconv.FormatBool(r.Jinja))
	s := r.Sampling
	write("temp", formatFloat(s.Temp))
	write("top-p", formatFloat(s.TopP))
	write("top-k", strconv.Itoa(s.TopK))
	write("min-p", formatFloat(s.MinP))
	write("repeat-penalty", formatFloat(s.RepeatPenalty))
	write("presence-penalty", formatFloat(s.PresencePenalty))
	write("frequency-penalty", formatFloat(s.FrequencyPenalty))
	write("typical-p", formatFloat(s.TypicalP))
	write("mirostat", strconv.Itoa(s.Mirostat))
	write("seed", strconv.Itoa(s.Seed))
}

func validateINISection(id string) error {
	if id == "" || strings.ContainsAny(id, "[]\r\n") {
		return fmt.Errorf("model id %q cannot be used as a models.ini section", id)
	}
	return nil
}

// iniValue rejects characters that would break a line-oriented INI file.
func iniValue(v string) string {
	v = strings.TrimSpace(v)
	v = strings.ReplaceAll(v, "\r", "")
	v = strings.ReplaceAll(v, "\n", " ")
	return v
}

func formatFloat(f float64) string {
	return strconv.FormatFloat(f, 'g', -1, 64)
}

// ConfigHash identifies the launch options in argv. Host and port are ignored
// because they do not change the model's performance shape; two servers with
// the same hash should be benchmark-compatible.
func ConfigHash(args []string) string {
	canonical := make([]string, 0, len(args))
	for i := 0; i < len(args); i++ {
		a := args[i]
		switch {
		case a == "--host" || a == "--port":
			i++
		case strings.HasPrefix(a, "--host="), strings.HasPrefix(a, "--port="):
			continue
		default:
			canonical = append(canonical, a)
		}
	}
	sum := sha256.Sum256([]byte(strings.Join(canonical, "\x00")))
	return hex.EncodeToString(sum[:6])
}

// CommandLine renders argv for logs and --dry-run output, quoting only when
// a value needs it.
func CommandLine(bin string, args []string) string {
	parts := make([]string, 0, len(args)+1)
	parts = append(parts, quoteArg(bin))
	for _, a := range args {
		parts = append(parts, quoteArg(a))
	}
	return strings.Join(parts, " ")
}

func quoteArg(s string) string {
	if s == "" {
		return "''"
	}
	if !strings.ContainsAny(s, " \t\n'\"\\$`;&|<>()*?[]{}#~!") {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
