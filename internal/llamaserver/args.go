// Package llamaserver builds llama-server command lines and talks to a
// running server's HTTP API.
package llamaserver

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"wool/internal/config"
)

// SingleArgs returns argv (without the binary) for a standalone server.
func SingleArgs(r config.Resolved, host string, port int) []string {
	args := []string{
		"--model", r.ModelPath,
		"--host", host,
		"--port", strconv.Itoa(port),
	}
	if r.Alias != "" {
		args = append(args, "--alias", r.Alias)
	}
	if r.Ctx > 0 {
		args = append(args, "-c", strconv.Itoa(r.Ctx))
	}
	args = append(args, "--gpu-layers", strconv.Itoa(r.GPULayers))
	if r.NCPUMoE > 0 {
		args = append(args, "--n-cpu-moe", strconv.Itoa(r.NCPUMoE))
	}
	if r.Threads > 0 {
		args = append(args, "--threads", strconv.Itoa(r.Threads))
	}
	if r.ThreadsBatch > 0 {
		args = append(args, "--threads-batch", strconv.Itoa(r.ThreadsBatch))
	}
	if r.BatchSize > 0 {
		args = append(args, "--batch-size", strconv.Itoa(r.BatchSize))
	}
	if r.UBatchSize > 0 {
		args = append(args, "--ubatch-size", strconv.Itoa(r.UBatchSize))
	}
	if r.Parallel > 0 {
		args = append(args, "--parallel", strconv.Itoa(r.Parallel))
	}
	if r.FlashAttn != "" {
		args = append(args, "--flash-attn", r.FlashAttn)
	}
	if r.CacheTypeK != "" {
		args = append(args, "--cache-type-k", r.CacheTypeK)
	}
	if r.CacheTypeV != "" {
		args = append(args, "--cache-type-v", r.CacheTypeV)
	}
	if r.Jinja {
		args = append(args, "--jinja")
	} else {
		args = append(args, "--no-jinja")
	}
	if r.Metrics {
		args = append(args, "--metrics")
	}
	args = append(args, samplingArgs(r.Sampling)...)
	args = append(args, extraArgs(r.Extra)...)
	return args
}

func samplingArgs(s config.Sampling) []string {
	return []string{
		"--temp", formatFloat(s.Temp),
		"--top-p", formatFloat(s.TopP),
		"--top-k", strconv.Itoa(s.TopK),
		"--min-p", formatFloat(s.MinP),
		"--repeat-penalty", formatFloat(s.RepeatPenalty),
		"--presence-penalty", formatFloat(s.PresencePenalty),
		"--frequency-penalty", formatFloat(s.FrequencyPenalty),
		"--typical-p", formatFloat(s.TypicalP),
		"--mirostat", strconv.Itoa(s.Mirostat),
		"--seed", strconv.Itoa(s.Seed),
	}
}

// extraArgs turns config extra keys into flags. A key may be written with or
// without leading dashes; an empty value produces a bare flag.
func extraArgs(extra map[string]string) []string {
	keys := make([]string, 0, len(extra))
	for k := range extra {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var args []string
	for _, k := range keys {
		flag := k
		if !strings.HasPrefix(flag, "-") {
			flag = "--" + flag
		}
		args = append(args, flag)
		if v := extra[k]; v != "" {
			args = append(args, v)
		}
	}
	return args
}

// RouterArgs returns argv for router mode. Per-model options come from the
// generated INI, never from the command line, because CLI flags would
// override every preset.
func RouterArgs(cfg *config.Config, host string, port int, iniPath string) []string {
	args := []string{
		"--host", host,
		"--port", strconv.Itoa(port),
		"--models-preset", iniPath,
		"--models-max", strconv.Itoa(cfg.Router.ModelsMax),
	}
	if cfg.Router.Autoload {
		args = append(args, "--models-autoload")
	} else {
		args = append(args, "--no-models-autoload")
	}
	if cfg.Router.SleepIdleSeconds >= 0 {
		args = append(args, "--sleep-idle-seconds", strconv.Itoa(cfg.Router.SleepIdleSeconds))
	}
	if cfg.Router.MetricsEnabled() {
		args = append(args, "--metrics")
	}
	if cfg.Router.MemoryMarginMiB > 0 {
		args = append(args, "--fit-target", strconv.Itoa(cfg.Router.MemoryMarginMiB))
	}
	return append(args, cfg.Router.ExtraArgs...)
}

// RenderRouterINI renders one preset section per model plus a [*] section
// holding the shared defaults. Sections are sorted for deterministic output.
func RenderRouterINI(cfg *config.Config) ([]byte, error) {
	defaults := cfg.ResolveDefaults()
	var b strings.Builder

	b.WriteString("# Generated by wool. Edits here are overwritten.\n")
	b.WriteString("[*]\n")
	writeCommonINI(&b, defaults)
	if cfg.Router.Autoload {
		b.WriteString("load-on-startup = true\n")
	}
	for _, id := range cfg.ModelIDs() {
		r, err := cfg.Resolve(id, nil)
		if err != nil {
			return nil, err
		}
		if err := validateINISection(id); err != nil {
			return nil, err
		}
		b.WriteString("\n[" + id + "]\n")
		b.WriteString("model = " + iniValue(r.ModelPath) + "\n")
		if r.Alias != "" {
			b.WriteString("alias = " + iniValue(r.Alias) + "\n")
		}
		writeCommonINI(&b, r)
		if len(r.Extra) > 0 {
			for _, k := range sortedKeys(r.Extra) {
				b.WriteString(k + " = " + iniValue(r.Extra[k]) + "\n")
			}
		}
	}
	return []byte(b.String()), nil
}

// WriteRouterINI writes the generated INI atomically, creating parent dirs.
func WriteRouterINI(cfg *config.Config, path string) error {
	data, err := RenderRouterINI(cfg)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), ".models-*.ini")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	defer os.Remove(tmpName)
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Chmod(0o600); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmpName, path)
}

// writeCommonINI writes launch options shared by the globals and each model.
func writeCommonINI(b *strings.Builder, r config.Resolved) {
	if r.Ctx > 0 {
		fmt.Fprintf(b, "ctx-size = %d\n", r.Ctx)
	}
	fmt.Fprintf(b, "gpu-layers = %d\n", r.GPULayers)
	if r.NCPUMoE > 0 {
		fmt.Fprintf(b, "n-cpu-moe = %d\n", r.NCPUMoE)
	}
	if r.Threads > 0 {
		fmt.Fprintf(b, "threads = %d\n", r.Threads)
	}
	if r.ThreadsBatch > 0 {
		fmt.Fprintf(b, "threads-batch = %d\n", r.ThreadsBatch)
	}
	if r.BatchSize > 0 {
		fmt.Fprintf(b, "batch-size = %d\n", r.BatchSize)
	}
	if r.UBatchSize > 0 {
		fmt.Fprintf(b, "ubatch-size = %d\n", r.UBatchSize)
	}
	if r.Parallel > 0 {
		fmt.Fprintf(b, "parallel = %d\n", r.Parallel)
	}
	if r.FlashAttn != "" {
		b.WriteString("flash-attn = " + iniValue(r.FlashAttn) + "\n")
	}
	if r.CacheTypeK != "" {
		b.WriteString("cache-type-k = " + iniValue(r.CacheTypeK) + "\n")
	}
	if r.CacheTypeV != "" {
		b.WriteString("cache-type-v = " + iniValue(r.CacheTypeV) + "\n")
	}
	fmt.Fprintf(b, "jinja = %t\n", r.Jinja)
	s := r.Sampling
	fmt.Fprintf(b, "temp = %s\n", formatFloat(s.Temp))
	fmt.Fprintf(b, "top-p = %s\n", formatFloat(s.TopP))
	fmt.Fprintf(b, "top-k = %d\n", s.TopK)
	fmt.Fprintf(b, "min-p = %s\n", formatFloat(s.MinP))
	fmt.Fprintf(b, "repeat-penalty = %s\n", formatFloat(s.RepeatPenalty))
	fmt.Fprintf(b, "presence-penalty = %s\n", formatFloat(s.PresencePenalty))
	fmt.Fprintf(b, "frequency-penalty = %s\n", formatFloat(s.FrequencyPenalty))
	fmt.Fprintf(b, "typical-p = %s\n", formatFloat(s.TypicalP))
	fmt.Fprintf(b, "mirostat = %d\n", s.Mirostat)
	fmt.Fprintf(b, "seed = %d\n", s.Seed)
}

func validateINISection(id string) error {
	if id == "" || strings.ContainsAny(id, "[]\r\n") {
		return fmt.Errorf("model id %q cannot be used as a models.ini section", id)
	}
	return nil
}

// iniValue rejects characters that would break a line-oriented INI file.
func iniValue(v string) string {
	v = strings.TrimSpace(v)
	v = strings.ReplaceAll(v, "\r", "")
	v = strings.ReplaceAll(v, "\n", " ")
	return v
}

func formatFloat(f float64) string {
	return strconv.FormatFloat(f, 'g', -1, 64)
}

func sortedKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// CommandLine renders argv for logs and --dry-run output, quoting only when
// a value needs it.
func CommandLine(bin string, args []string) string {
	parts := make([]string, 0, len(args)+1)
	parts = append(parts, quoteArg(bin))
	for _, a := range args {
		parts = append(parts, quoteArg(a))
	}
	return strings.Join(parts, " ")
}

func quoteArg(s string) string {
	if s == "" {
		return "''"
	}
	if !strings.ContainsAny(s, " \t\n'\"\\$`;&|<>()*?[]{}#~!") {
		return s
	}
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}
